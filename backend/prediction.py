"""Validated input conversion and inference for the final notebook model."""
from datetime import date as Date
import json
from pathlib import Path
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from pydantic import BaseModel, ConfigDict, Field

ARTIFACTS = Path(__file__).resolve().parents[1] / 'artifacts'


class PredictionInput(BaseModel):
    model_config = ConfigDict(extra='forbid', allow_inf_nan=False)
    date: Date
    hour: int = Field(ge=0, le=23)
    season: Literal[1, 2, 3, 4]
    weather: Literal[1, 2, 3, 4]
    temperature_c: float = Field(ge=-8, le=39)
    humidity: float = Field(ge=0, le=100)
    wind_kmh: float = Field(ge=0, le=67)
    holiday: bool
    baseline_year: Literal[2011, 2012]


class Predictor:
    def __init__(self):
        # Only load the trusted local artifact generated by prepare_model.py.
        bundle = joblib.load(ARTIFACTS / 'ridge_model.joblib')
        self.model = bundle['model']
        self.columns = bundle['features']
        self.metadata = json.loads((ARTIFACTS / 'metadata.json').read_text(encoding='utf-8'))
        self.scenarios = json.loads((ARTIFACTS / 'scenarios.json').read_text(encoding='utf-8'))
        if list(self.model.feature_names_in_) != self.columns:
            raise ValueError('Model artifact feature order is inconsistent.')

    def features(self, inputs: PredictionInput, hours=None):
        weekday = (inputs.date.weekday() + 1) % 7  # UCI: Sunday = 0.
        workingday = int(weekday not in [0, 6] and not inputs.holiday)
        rows = []
        for hour in ([inputs.hour] if hours is None else hours):
            row = dict.fromkeys(self.columns, 0.0)
            row.update({
                'yr': inputs.baseline_year - 2011,
                'holiday': int(inputs.holiday), 'workingday': workingday,
                'temp': (inputs.temperature_c + 8) / 47,
                'hum': inputs.humidity / 100, 'windspeed': inputs.wind_kmh / 67,
                'rush_hour_commute': int(workingday and hour in [7, 8, 9, 17, 18, 19]),
            })
            for name, value in [('season', inputs.season), ('weathersit', inputs.weather),
                                ('weekday', weekday), ('hr', hour), ('mnth', inputs.date.month)]:
                column = f'{name}_{value}'
                if column in row:
                    row[column] = 1.0
            rows.append(row)
        return pd.DataFrame(rows, columns=self.columns)

    def predict(self, inputs: PredictionInput):
        values = np.maximum(self.model.predict(self.features(inputs, range(24))), 0)
        warnings = []
        if inputs.date.year not in [2011, 2012]:
            warnings.append(f'This date is outside the 2011–2012 dataset. Estimates use the {inputs.baseline_year} demand baseline, not current ridership.')
        elif inputs.date.year != inputs.baseline_year:
            warnings.append(f'The selected date uses the {inputs.baseline_year} demand baseline rather than its calendar year.')
        if inputs.weather == 4:
            warnings.append('Heavy weather has only a few training observations. Treat this estimate with particular caution.')
        if inputs.humidity == 0:
            warnings.append('Zero humidity is an extreme condition. The model may be less reliable here.')
        value = float(values[inputs.hour])
        weekday = (inputs.date.weekday() + 1) % 7
        return {
            'prediction': value, 'rentals': int(np.rint(value)),
            'inputs': inputs.model_dump(mode='json'),
            'profile': [{'hour': i, 'prediction': float(v), 'rentals': int(np.rint(v))} for i, v in enumerate(values)],
            'peak_hour': int(np.argmax(values)),
            'workingday': weekday not in [0, 6] and not inputs.holiday,
            'warnings': warnings,
        }
